"""Scalar domain checks shared by the statistics closures (legacy messages)."""

from __future__ import annotations

import math

__all__ = ["finite_nonnegative", "finite_positive"]


def finite_positive(value: float, name: str) -> float:
    result = float(value)
    if not math.isfinite(result) or result <= 0.0:
        raise ValueError(f"{name} must be finite and positive")
    return result


def finite_nonnegative(value: float, name: str) -> float:
    result = float(value)
    if not math.isfinite(result) or result < 0.0:
        raise ValueError(f"{name} must be finite and non-negative")
    return result
