/** Structural editable inputs only; Python owns numeric, unit and semantic validation. */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { compile } from 'json-schema-to-typescript';
import ts from 'typescript';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const compiler = require('json-schema-to-typescript/package.json');
const project = JSON.parse(await readFile(resolve(web, 'package.json'), 'utf8'));
if (project.devDependencies['json-schema-to-typescript'] !== compiler.version) {
  throw new Error('Install the exact locked json-schema-to-typescript development dependency.');
}
const { values } = parseArgs({
  options: {
    check: { type: 'boolean', default: false },
    python: { type: 'string', default: process.env.SOLARLAB_PYTHON || 'python3' },
    output: { type: 'string', default: resolve(web, 'src/generated/configuration-inputs.ts') },
  },
});
const source = spawnSync(values.python, ['-B', resolve(web, '../scripts/generate_configuration_schema.py'), '--json'], {
  encoding: 'utf8', maxBuffer: 4 * 1024 ** 2, timeout: 15000,
});
if (source.error || source.status !== 0) {
  throw new Error(`Configuration schema export failed: ${source.error?.message || source.stderr}`);
}
const bundle = JSON.parse(source.stdout);
if (bundle.schema_version !== 'solarlab.configuration-schema-export.v1') {
  throw new Error('Unsupported configuration metadata version.');
}

function checkLocalReferences(value) {
  if (Array.isArray(value)) value.forEach(checkLocalReferences);
  else if (value && typeof value === 'object') {
    if ('$ref' in value && !value.$ref.startsWith('#/')) {
      throw new Error(`Only independent local schema references are supported: ${value.$ref}`);
    }
    Object.values(value).forEach(checkLocalReferences);
  }
}

function checkDeclarations(text, name) {
  const tree = ts.createSourceFile(`${name}.d.ts`, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  if (tree.parseDiagnostics.length || !tree.statements.some(node =>
    (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) && node.name.text === name)) {
    throw new Error(`Compiler did not produce the declared input root: ${name}`);
  }
  function inspect(node) {
    if ([ts.SyntaxKind.AnyKeyword, ts.SyntaxKind.UnknownKeyword].includes(node.kind)) {
      throw new Error(`Compiler emitted an unconstrained type for ${name}; schema support needs review.`);
    }
    ts.forEachChild(node, inspect);
  }
  tree.statements.forEach(node => {
    if (!ts.isInterfaceDeclaration(node) && !ts.isTypeAliasDeclaration(node)) {
      throw new Error(`Non-structural compiler declaration for ${name}.`);
    }
    inspect(node);
  });
}

const output = [
  '// Generated by web/scripts/generate-configuration-inputs.mjs; do not edit.',
  `// Compiler: json-schema-to-typescript ${compiler.version} (locked development dependency).`,
  '// Structural editable inputs only; backend DTO validators remain authoritative.',
  '// TypeScript does not validate numeric bounds, units, string patterns or cross-field semantics.',
  '// Excess-property checks apply to fresh object literals; these are not runtime validators.',
  '// Each ambient namespace isolates one complete Python schema reference graph.',
  '// Normalized/resolved/result types, protocol envelopes and production integration remain pending.',
  '',
];
for (const [name, entry] of Object.entries(bundle.dto_schemas).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) || entry.representation !== 'editable_input') {
    throw new Error(`Unsupported editable DTO entry: ${name}`);
  }
  checkLocalReferences(entry.schema);
  const digest = createHash('sha256').update(JSON.stringify(entry.schema)).digest('hex');
  const declaration = await compile(structuredClone(entry.schema), name, {
    bannerComment: '', unknownAny: true, declareExternallyReferenced: true,
    unreachableDefinitions: true,
    $refOptions: { resolve: { file: false, http: false } },
    style: { singleQuote: true, semi: true, tabWidth: 2, printWidth: 100 },
  });
  checkDeclarations(declaration, name);
  output.push(`// Source DTO: ${entry.python_type}`);
  output.push(`// Schema SHA-256 (JSON.stringify): ${digest}`);
  output.push(`export declare namespace ${name}Definitions {`);
  output.push(declaration.trimEnd().split('\n').map(line => line ? `  ${line}` : '').join('\n'));
  output.push('}', `export type ${name} = ${name}Definitions.${name};`, '');
}
const expected = output.join('\n');
if (Buffer.byteLength(expected) > 4 * 1024 ** 2) throw new Error('Generated input types exceed 4 MiB.');
if (values.check) {
  const actual = await readFile(values.output, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (actual !== expected) {
    console.error(`Stale or missing configuration input types: ${values.output}`);
    process.exitCode = 1;
  } else console.log(`Configuration input types are current: ${values.output}`);
} else {
  await mkdir(dirname(resolve(values.output)), { recursive: true });
  await writeFile(values.output, expected, 'utf8');
  console.log(`Generated configuration input types: ${values.output}`);
}
